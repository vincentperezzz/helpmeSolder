// Draws the original (CC0) wiring-diagram SVGs for parts that have no Wokwi
// element, and writes src/lib/catalog/part-drawings.generated.ts with each
// drawing's size and the point every catalog pin's wire ends on. Generating the
// picture and the terminals together keeps them from drifting apart.
//
//   npm run gen:part-drawings                    every family: SVGs and the .ts file
//   npm run gen:part-drawings -- --only=sensors  one family's SVGs only
//
// Each scripts/drawings/<family>.mjs default-exports a list of functions that
// each return one drawing: { id, kind: "board" | "module", file, caption, title,
// comment, width, height, body, terminals, pinExit? }. Files starting with "_"
// are shared helpers, not families. Header orders follow each part's published
// pinout (physical layout facts only, no third-party artwork).
// src/lib/catalog/part-drawings.test.ts checks that every catalog pin has a terminal.
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { svgDoc } from "./drawings/_lib.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "scripts/drawings");
const LICENSE = "CC0 - HelpmeSolder original SVG";
const only = process.argv.find((a) => a.startsWith("--only="))?.slice("--only=".length);

const families = readdirSync(dir)
  .filter((f) => f.endsWith(".mjs") && !f.startsWith("_"))
  .map((f) => f.replace(/\.mjs$/, ""))
  .sort();

const drawings = [];
for (const family of families) {
  if (only && family !== only) continue;
  const mod = await import(pathToFileURL(path.join(dir, `${family}.mjs`)).href);
  for (const make of mod.default) drawings.push({ family, ...make() });
}

const seen = new Set();
for (const d of drawings) {
  if (seen.has(d.id)) throw new Error(`Two drawings for ${d.id}`);
  seen.add(d.id);
  const svg = svgDoc({ width: d.width, height: d.height, title: d.title, comment: d.comment, body: d.body });
  const file = path.join(root, "public/assets", d.file);
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, svg);
}

if (only) {
  console.log(`Wrote ${drawings.length} drawings for ${only} (generated .ts not touched)`);
} else {
  const entry = (d) => {
    const terminals = Object.entries(d.terminals)
      .map(([k, p]) => `      ${JSON.stringify(k)}: { x: ${p.x}, y: ${p.y} },`)
      .join("\n");
    return [
      `  ${JSON.stringify(d.id)}: {`,
      `    src: ${JSON.stringify(`/assets/${d.file}`)},`,
      `    width: ${d.width},`,
      `    height: ${d.height},`,
      `    caption: ${JSON.stringify(d.caption)},`,
      `    license: ${JSON.stringify(LICENSE)},`,
      d.pinExit ? `    pinExit: { dx: ${d.pinExit.dx}, dy: ${d.pinExit.dy} },` : null,
      `    terminals: {`,
      terminals,
      `    },`,
      `  },`,
    ]
      .filter((line) => line !== null)
      .join("\n");
  };

  const ts = [
    "// GENERATED by scripts/gen-part-drawings.mjs. Do not edit; run `npm run gen:part-drawings`.",
    'import type { BoardAsset } from "./board-assets";',
    "",
    "export const GENERATED_BOARD_ASSETS: Record<string, BoardAsset> = {",
    ...drawings.filter((d) => d.kind === "board").map(entry),
    "};",
    "",
    "export const GENERATED_MODULE_ASSETS: Record<string, BoardAsset> = {",
    ...drawings.filter((d) => d.kind === "module").map(entry),
    "};",
    "",
  ].join("\n");
  writeFileSync(path.join(root, "src/lib/catalog/part-drawings.generated.ts"), ts);
  console.log(`Wrote ${drawings.length} drawings and src/lib/catalog/part-drawings.generated.ts`);
}
